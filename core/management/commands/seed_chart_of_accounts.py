class Command(BaseCommand):
    help = "إضافة الدليل المحاسبي الموحد (Odoo ERP Architecture) إلى جميع الشركات"

    def handle(self, *args, **options):
        companies = Company.objects.all()
        if not companies.exists():
            self.stdout.write(self.style.WARNING("لا توجد شركات مسجلة في النظام. يرجى إنشاء شركة أولاً."))
            return

        for company in companies:
            created_count = 0
            updated_count = 0
            for code, name, acc_type in CHART_OF_ACCOUNTS:
                acc, created = Account.objects.update_or_create(
                    company=company,
                    code=code,
                    defaults={"name": name, "type": acc_type}
                )
                if created:
                    created_count += 1
                else:
                    updated_count += 1

            self.stdout.write(
                self.style.SUCCESS(
                    f"تم تحديث الدليل المحاسبي للشركة '{company.name}': {created_count} حساب جديد، {updated_count} حساب محدّث."
                )
            )
